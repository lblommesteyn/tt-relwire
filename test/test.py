"""Three cores on one chip run the same I2C program as controller, target and
sniffer. The test programs the chip over its pins, lets the transaction run,
then reads every core's data memory back and compares it, bit by bit, with
the RelWire reference model (expected.txt, from tools/gen_tt_test)."""

import os

import cocotb
from cocotb.clock import Clock
from cocotb.triggers import ClockCycles, FallingEdge

HERE = os.path.dirname(os.path.abspath(__file__))
TICK_CYCLES = 11  # 5 + 2 (pin synchronizer) + 4 cores


def read_vectors():
    with open(os.path.join(HERE, "load.hex")) as f:
        stream = [int(l, 16) for l in f if l.strip()]
    with open(os.path.join(HERE, "expected.txt")) as f:
        lines = [l.split() for l in f if l.strip()]
    ticks = int(lines[0][2])
    expected = {int(c): bits for c, bits in lines[1:]}
    return stream, ticks, expected


async def send(dut, byte):
    # change inputs on the falling edge so RTL and gate-level runs agree on
    # which rising edge first sees them
    await FallingEdge(dut.clk)
    dut.ui_in.value = byte
    await ClockCycles(dut.clk, 2, rising=False)
    dut.load_strobe.value = 1
    await ClockCycles(dut.clk, 3, rising=False)
    dut.load_strobe.value = 0
    await ClockCycles(dut.clk, 3, rising=False)


# Symmetry. The four cores are identical, the four protocol wires are
# interchangeable, and a role id is only a label. So relabelling any of the
# three in the loader stream must relabel the result and change nothing else:
# run(g . config) == g . run(config) for every g in S4 x S4 x S4. That
# property composes, and S4 is generated by one swap and one 4-cycle, so two
# checks per action cover all 24 permutations (six checks, 13 824 symmetries).
IDENT = (0, 1, 2, 3)
SWAP = (1, 0, 2, 3)
CYCLE = (1, 2, 3, 0)
CMD_LEN = {1: 6, 2: 4, 3: 4, 4: 3, 5: 3, 6: 1, 7: 1, 8: 3}
WIRE_OPS = (1, 2, 3, 5, 6)  # EDGE, PUT, SAMPLE, TOGGLE, BRANCH_RUN use the wire field


def relabel(stream, cores, wires, roles):
    """The loader stream with core i renamed cores[i], wire w renamed wires[w]
    and role r renamed roles[r]."""
    out, i = [], 0
    while i < len(stream):
        c = list(stream[i : i + CMD_LEN[stream[i]]])
        i += len(c)
        if c[0] == 0x01:  # program word: [25:24] role, [23:20] op, [19] owned, [18:17] wire
            w = ((c[2] & 3) << 24) | (c[3] << 16) | (c[4] << 8) | c[5]
            op = (w >> 20) & 15
            if (w >> 19) & 1:
                w = (w & ~(3 << 24)) | (roles[(w >> 24) & 3] << 24)
            if op in WIRE_OPS:
                w = (w & ~(3 << 17)) | (wires[(w >> 17) & 3] << 17)
            c[2:6] = [(c[2] & 0xFC) | (w >> 24), (w >> 16) & 0xFF, (w >> 8) & 0xFF, w & 0xFF]
        elif c[0] == 0x03:  # data-memory byte of one core
            c[1] = cores[c[1]]
        elif c[0] == 0x04:  # role mask of one core
            c[1] = cores[c[1]]
            c[2] = sum(1 << roles[r] for r in range(4) if (c[2] >> r) & 1)
        elif c[0] == 0x05:  # wire resolution
            c[1] = wires[c[1]]
        out += c
    return out


async def run_case(dut, cores=IDENT, wires=IDENT, roles=IDENT):
    stream, ticks, expected = read_vectors()
    stream = relabel(stream, cores, wires, roles)
    expected = {cores[c]: bits for c, bits in expected.items()}
    cocotb.start_soon(Clock(dut.clk, 20, unit="ns").start())
    dut.ena.value = 1
    dut.ui_in.value = 0
    dut.load_strobe.value = 0
    dut.load_frame.value = 0
    dut.rst_n.value = 0
    await ClockCycles(dut.clk, 10)
    dut.rst_n.value = 1
    await ClockCycles(dut.clk, 4)

    for b in stream:  # ends with 06: run
        await send(dut, b)
    await ClockCycles(dut.clk, ticks * TICK_CYCLES)
    assert int(dut.uo_out.value) & 0x40, "all cores should have halted"
    await send(dut, 0x07)  # stop

    for core, want in expected.items():
        got = []
        for byte in range(8):
            await send(dut, 0x08)
            await send(dut, core)
            await send(dut, byte)
            await ClockCycles(dut.clk, 2, rising=False)
            v = int(dut.uo_out.value)
            got += [(v >> j) & 1 for j in range(8)]
        for j, w in enumerate(want):
            if w != "-":
                assert got[j] == int(w), f"core {core} bit {j}: got {got[j]}, model says {w}"
        dut._log.info(f"core {core}: {sum(w != '-' for w in want)} bits match the model")


@cocotb.test()
async def test_i2c_three_roles_one_binary(dut):
    await run_case(dut)


@cocotb.test()
async def test_symmetry_cores_swap(dut):
    await run_case(dut, cores=SWAP)


@cocotb.test()
async def test_symmetry_cores_cycle(dut):
    await run_case(dut, cores=CYCLE)


@cocotb.test()
async def test_symmetry_wires_swap(dut):
    await run_case(dut, wires=SWAP)


@cocotb.test()
async def test_symmetry_wires_cycle(dut):
    await run_case(dut, wires=CYCLE)


@cocotb.test()
async def test_symmetry_roles_swap(dut):
    await run_case(dut, roles=SWAP)


@cocotb.test()
async def test_symmetry_roles_cycle(dut):
    await run_case(dut, roles=CYCLE)
